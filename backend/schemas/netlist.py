"""Typed contract for the Yosys JSON netlist (``estrutura.json``).

The models keep the exact shape produced by ``write_json`` so the frontend can
correlate ports, cells and nets by Yosys bit identifiers. The backend adds
``width`` (``len(bits)``) to ports and nets. Unknown fields emitted by other
Yosys versions are accepted and preserved (``extra="allow"``).
"""

from typing import Annotated, Any, Literal, Self

from pydantic import BaseModel, ConfigDict, Field, StrictInt, model_validator

type ConstantBit = Literal["0", "1", "x", "z"]
"""Constant logic value used by Yosys in place of a net identifier."""

type Bit = Annotated[
    StrictInt | ConstantBit,
    Field(description="Yosys net identifier (integer) or constant `0`/`1`/`x`/`z`."),
]

type Direction = Literal["input", "output", "inout"]

type AttributeValue = Annotated[
    str | StrictInt,
    Field(
        description=(
            "Yosys attribute/parameter value: binary string for constants "
            "(e.g. `00000000000000000000000000000001`), plain text, or integer."
        )
    ),
]


class _YosysModel(BaseModel):
    model_config = ConfigDict(extra="allow")


class _WithWidth(_YosysModel):
    """Bit vector whose ``width`` is derived from ``bits``."""

    bits: list[Bit] = Field(..., description="Bits of the signal, LSB first.")
    width: int = Field(..., ge=0, description="Number of bits (`len(bits)`).")

    @model_validator(mode="before")
    @classmethod
    def _fill_width(cls, data: Any) -> Any:
        if isinstance(data, dict) and "width" not in data and isinstance(data.get("bits"), list):
            return {**data, "width": len(data["bits"])}
        return data

    @model_validator(mode="after")
    def _check_width(self) -> Self:
        if self.width != len(self.bits):
            raise ValueError("width must equal the number of bits")
        return self


class NetlistPort(_WithWidth):
    """Module port."""

    direction: Direction


class NetlistCell(_YosysModel):
    """Cell (component) instance: a primitive such as `$add` or a submodule."""

    hide_name: int = Field(..., description="1 when Yosys generated the name.")
    type: str = Field(..., description="Cell type (`$add`, `$mux`, submodule name...).")
    parameters: dict[str, AttributeValue] = Field(default_factory=dict)
    attributes: dict[str, AttributeValue] = Field(default_factory=dict)
    port_directions: dict[str, Direction] = Field(
        default_factory=dict,
        description="Direction of each cell port; absent for unknown black boxes.",
    )
    connections: dict[str, list[Bit]] = Field(..., description="Bits connected to each cell port.")


class NetlistNet(_WithWidth):
    """Named wire (``netnames``)."""

    hide_name: int = Field(..., description="1 when Yosys generated the name.")
    attributes: dict[str, AttributeValue] = Field(default_factory=dict)


class NetlistModule(_YosysModel):
    """Synthesized module."""

    attributes: dict[str, AttributeValue] = Field(default_factory=dict)
    parameter_default_values: dict[str, AttributeValue] | None = Field(None, exclude_if=lambda value: value is None)
    ports: dict[str, NetlistPort] = Field(default_factory=dict)
    cells: dict[str, NetlistCell] = Field(default_factory=dict)
    netnames: dict[str, NetlistNet] = Field(default_factory=dict)

    @property
    def is_top(self) -> bool:
        """Whether Yosys marked this module as top (``hierarchy -auto-top``)."""
        return _is_set(self.attributes.get("top"))


class Netlist(_YosysModel):
    """Netlist generated by ``write_json``."""

    creator: str = Field(..., description="Yosys version that produced the file.")
    modules: dict[str, NetlistModule] = Field(..., min_length=1)

    @model_validator(mode="after")
    def _check_top(self) -> Self:
        tops = [name for name, module in self.modules.items() if module.is_top]
        if len(tops) != 1:
            raise ValueError(f"expected exactly one module with the 'top' attribute, found {len(tops)}")
        return self

    @property
    def top_module(self) -> str:
        """Name of the module selected by ``hierarchy -auto-top``."""
        return next(name for name, module in self.modules.items() if module.is_top)


def _is_set(value: AttributeValue | None) -> bool:
    if isinstance(value, int):
        return value != 0
    if isinstance(value, str) and value and set(value) <= {"0", "1"}:
        return "1" in value
    return False
