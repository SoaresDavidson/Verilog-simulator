"""Icarus Verilog simulation integration executed through Docker."""

import logging
import time
from dataclasses import dataclass, field, replace
from pathlib import Path, PurePosixPath
from typing import Any

from .docker import (
    DockerCommandResult,
    DockerConfig,
    DockerConnectionError,
    DockerContainerNotFoundError,
    DockerContainerUnavailableError,
    DockerExecutionError,
    DockerIntegration,
    DockerResourceLimitError,
    DockerTimeoutError,
    ExecutionMode,
)
from .projects import (
    grant_run_access,
    is_fresh_artifact,
    remove_artifacts,
    resolve_project_dir,
    run_mount,
    validate_relative_source,
)
from .vcd import VcdFormatError, VcdLimits, VcdSelection, parse_vcd

logger = logging.getLogger(__name__)

COMPILATION_FAILED_EXIT_CODE = 10
"""Exit code used by ``simular.sh`` when ``iverilog`` rejects the sources."""

SIMULATION_FAILED_EXIT_CODE = 11
"""Exit code used by ``simular.sh`` when ``vvp`` exits unsuccessfully."""

_SCRIPT_MISSING_EXIT_CODES = frozenset({126, 127})


@dataclass(frozen=True, slots=True)
class IcarusConfig:
    """Runtime settings for Icarus Verilog simulation."""

    container_name: str = "icarus-verilog"
    timeout_seconds: float = 30
    verilog_base_dir: Path = Path("/verilog_code")
    script_path: str = "/scripts/simular.sh"
    docker_host: str | None = None
    run_owner: tuple[int, int] | None = None
    """``(uid, gid)`` that receives the run before execution; ``None`` keeps it."""
    execution_mode: ExecutionMode = ExecutionMode.EPHEMERAL
    image: str = "verilog-classroom/icarus:latest"
    """Image of the per-execution container (``ephemeral`` mode)."""
    host_verilog_root: str | None = None
    """Path of ``verilog_base_dir`` on the Docker host (``None``: same as local)."""
    host_scripts_dir: str | None = None
    """Host directory mounted read-only at the parent of ``script_path``
    (``ephemeral`` mode). ``None`` mounts nothing: the image must ship the script."""
    vcd_limits: VcdLimits = field(default_factory=VcdLimits)

    def __post_init__(self) -> None:
        """Validate configuration values."""
        object.__setattr__(self, "execution_mode", ExecutionMode(self.execution_mode))
        if not self.image.strip():
            raise ValueError("Icarus image cannot be empty.")
        if not self.container_name.strip():
            raise ValueError("Icarus container name cannot be empty.")
        if self.timeout_seconds <= 0:
            raise ValueError("Icarus timeout must be greater than zero.")
        if not self.verilog_base_dir.is_absolute():
            raise ValueError("Icarus Verilog base directory must be absolute.")
        if not PurePosixPath(self.script_path).is_absolute():
            raise ValueError("Icarus script path must be absolute.")


@dataclass(frozen=True, slots=True)
class IcarusResult:
    """Structured result of an Icarus Verilog execution."""

    success: bool
    exit_code: int
    stdout: str
    stderr: str
    vcd_file: Path | None = None
    simulation_log: dict[str, Any] | None = None


class IcarusError(Exception):
    """Base error for Icarus Verilog integration failures."""


class IcarusContainerNotFoundError(IcarusError):
    """Raised when the Icarus container or Docker daemon is unavailable."""


class IcarusResourceLimitError(IcarusError):
    """Raised when the execution is killed for exceeding a resource limit.

    The message is in pt-BR and safe to show to the student; ``limit`` names
    the exhausted resource (``"memory"``).
    """

    def __init__(self, message: str, limit: str = "memory") -> None:
        super().__init__(message)
        self.limit = limit


class IcarusTimeoutError(IcarusError):
    """Raised when the simulation exceeds the configured timeout."""

    def __init__(self, message: str, timeout_seconds: float) -> None:
        super().__init__(message)
        self.timeout_seconds = timeout_seconds


class _IcarusResultError(IcarusError):
    """Icarus error that preserves the execution result."""

    def __init__(self, message: str, result: IcarusResult) -> None:
        super().__init__(message)
        self.result = result


class IcarusCompilationError(_IcarusResultError):
    """Raised when ``iverilog`` rejects the project sources."""


class IcarusSimulationError(_IcarusResultError):
    """Raised when ``vvp`` (or the simulation script) exits unsuccessfully."""


class VcdParseError(_IcarusResultError):
    """Raised when the VCD generated by the simulation cannot be parsed."""


class IcarusIntegration:
    """Build and execute Icarus Verilog simulations in Docker."""

    def __init__(
        self,
        config: IcarusConfig | None = None,
        docker_integration: DockerIntegration | None = None,
    ) -> None:
        """Initialize integration.

        Args:
            config: Icarus and Docker runtime settings.
            docker_integration: Reusable Docker integration.
        """
        self.config = config or IcarusConfig()
        self.docker = docker_integration or DockerIntegration(
            DockerConfig(
                docker_host=self.config.docker_host,
                timeout_seconds=self.config.timeout_seconds,
            )
        )

    def build_command(self, verilog_files: list[Path]) -> list[str]:
        """Build the simulation command for relative Verilog source paths.

        Args:
            verilog_files: Source paths relative to the project directory.

        Returns:
            Docker exec argument list.

        Raises:
            ValueError: If source list is empty or contains unsafe paths.
        """
        if not verilog_files:
            raise ValueError("At least one Verilog source file is required.")
        sources = [validate_relative_source(source) for source in verilog_files]
        return ["bash", PurePosixPath(self.config.script_path).as_posix(), *sources]

    def simulate(
        self, project_id: str, selection: VcdSelection | None = None
    ) -> IcarusResult:
        """Compile and simulate a project, returning its parsed waveform.

        Args:
            project_id: Safe project path below ``runs/run_<id>``.
            selection: Optional waveform slice (time window, signals, decimation).

        Returns:
            Successful execution result. ``simulation_log`` is ``None`` when the
            testbench does not dump a VCD file.

        Raises:
            FileNotFoundError: If project or Verilog sources do not exist.
            NotADirectoryError: If project path is not a directory.
            ValueError: If project ID is unsafe.
            IcarusContainerNotFoundError: If container or daemon is unavailable.
            IcarusTimeoutError: If execution exceeds configured timeout.
            IcarusResourceLimitError: If execution is killed by the memory limit.
            IcarusCompilationError: If ``iverilog`` rejects the sources.
            IcarusSimulationError: If the simulation exits unsuccessfully.
            VcdParseError: If the generated VCD cannot be parsed.
        """
        project_dir, container_dir = resolve_project_dir(
            self.config.verilog_base_dir, project_id
        )
        command = self.build_command(self._find_verilog_sources(project_dir))
        remove_artifacts(list(project_dir.rglob("*.vcd")))
        if self.config.run_owner is not None:
            grant_run_access(project_dir, *self.config.run_owner)
        started_at = time.time()

        try:
            execution = self._run(command, project_dir, container_dir)
        except DockerResourceLimitError as exc:
            raise IcarusResourceLimitError(str(exc), exc.limit) from exc
        except (
            DockerConnectionError,
            DockerContainerNotFoundError,
            DockerContainerUnavailableError,
        ) as exc:
            raise IcarusContainerNotFoundError(str(exc)) from exc
        except DockerTimeoutError as exc:
            raise IcarusTimeoutError(
                f"Icarus simulation exceeded {self.config.timeout_seconds:g} seconds.",
                self.config.timeout_seconds,
            ) from exc
        except DockerExecutionError as exc:
            raise IcarusError(f"Icarus Docker execution failed: {exc}") from exc

        result = IcarusResult(
            success=execution.exit_code == 0,
            exit_code=execution.exit_code,
            stdout=execution.stdout,
            stderr=execution.stderr,
        )
        self._raise_for_exit_code(result)

        vcd_file = self._find_vcd(project_dir, started_at)
        if vcd_file is None:
            return result
        result = replace(result, vcd_file=vcd_file)

        try:
            simulation_log = parse_vcd(vcd_file, selection, self.config.vcd_limits)
        except VcdFormatError as exc:
            logger.warning("Failed to parse VCD for %s: %s", project_id, exc)
            raise VcdParseError(
                "Simulation finished but its VCD file could not be parsed.", result
            ) from exc
        return replace(result, simulation_log=simulation_log)

    def _run(
        self, command: list[str], project_dir: Path, container_dir: str
    ) -> DockerCommandResult:
        """Execute ``command`` in the configured mode (see ``ExecutionMode``)."""
        if self.config.execution_mode is ExecutionMode.EXEC:
            return self.docker.execute(
                container_name=self.config.container_name,
                command=command,
                workdir=container_dir,
                timeout_seconds=self.config.timeout_seconds,
            )
        run_dir_host, run_dir_container = run_mount(
            self.config.verilog_base_dir, project_dir, self.config.host_verilog_root
        )
        scripts = (
            {self.config.host_scripts_dir: PurePosixPath(self.config.script_path).parent.as_posix()}
            if self.config.host_scripts_dir
            else None
        )
        return self.docker.run_ephemeral(
            image=self.config.image,
            command=command,
            run_dir_host=run_dir_host,
            run_dir_container=run_dir_container,
            workdir=container_dir,
            timeout_seconds=self.config.timeout_seconds,
            read_only_mounts=scripts,
        )

    def _raise_for_exit_code(self, result: IcarusResult) -> None:
        exit_code = result.exit_code
        if exit_code == 0:
            return
        if exit_code == COMPILATION_FAILED_EXIT_CODE:
            raise IcarusCompilationError(
                "iverilog failed to compile the project.", result
            )
        if exit_code in _SCRIPT_MISSING_EXIT_CODES:
            raise IcarusError(
                f"Simulation script '{self.config.script_path}' could not be executed "
                f"(exit code {exit_code})."
            )
        raise IcarusSimulationError(
            f"Simulation failed with exit code {exit_code}.", result
        )

    @staticmethod
    def _find_verilog_sources(project_dir: Path) -> list[Path]:
        sources = [
            path.relative_to(project_dir)
            for path in project_dir.rglob("*")
            if path.is_file() and path.suffix.lower() in {".v", ".sv"}
        ]
        sources.sort(key=lambda path: path.as_posix())
        if not sources:
            raise FileNotFoundError(
                f"No Verilog (.v or .sv) files found in '{project_dir.name}' for simulation."
            )
        return sources

    @staticmethod
    def _find_vcd(project_dir: Path, started_at: float) -> Path | None:
        """Pick the VCD produced by this run.

        Only files written after ``started_at`` are candidates (old dumps were
        removed before the run; the mtime check covers a failed removal). With
        several candidates the most recently modified wins, ties broken by path.
        """
        candidates = [
            path
            for path in project_dir.rglob("*.vcd")
            if is_fresh_artifact(path, started_at)
        ]
        if not candidates:
            return None
        candidates.sort(key=lambda path: (path.stat().st_mtime, path.as_posix()))
        chosen = candidates[-1]
        if len(candidates) > 1:
            logger.warning(
                "Simulation produced %d VCD files; using most recent '%s'.",
                len(candidates),
                chosen.relative_to(project_dir).as_posix(),
            )
        return chosen
